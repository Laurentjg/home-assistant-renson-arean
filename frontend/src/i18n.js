export function languageOf(hass) {
  const language = (hass && ((hass.locale && hass.locale.language) || hass.language)) || 'en';
  return String(language).toLowerCase().startsWith('nl') ? 'nl' : 'en';
}

export function t(lang, key) {
  const table = STRINGS[lang] || STRINGS.en;
  return table[key] !== undefined ? table[key] : STRINGS.en[key];
}

export function hasString(key) {
  return STRINGS.en[key] !== undefined;
}
